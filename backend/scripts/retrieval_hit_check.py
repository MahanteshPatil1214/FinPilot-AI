
"""Retrieval-only evaluation: Hit@1, Hit@5, MRR and abstention.

No LLM or Groq calls. Uses synthetic PDFs generated by generate_fixtures.py.

Run from the repository root:
    python backend/scripts/retrieval_hit_check.py

Optional database override:
    BENCH_DATABASE_URL=...
"""

import json
import os
import sys
import uuid
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]
REPO_ROOT = BACKEND_DIR.parent
DATA_DIR = REPO_ROOT / "data" / "synthetic"

os.environ["DATABASE_URL"] = os.environ.get(
    "BENCH_DATABASE_URL", "sqlite:///:memory:"
)
sys.path.insert(0, str(BACKEND_DIR))

from app.db.init_db import init_db
from app.db.session import SessionLocal
from app.models.document import Document
from app.models.document_page import DocumentPage
from app.models.document_chunk import DocumentChunk
from app.services import document_parser, indexing_service, retrieval_service
from app.services.embedding_service import SentenceTransformerEmbeddingProvider
from app.core.config import settings

ORG = "org_hit"

ANSWERABLE_QUESTIONS = [
    ("What is the invoice number on the tax invoice?", "inv-2026-0001"),
    ("What is the total amount on invoice INV-2026-0001?", "12,000.00"),
    ("What is the invoice date?", "05/01/2026"),
    ("What is the due date on the invoice?", "05/02/2026"),
    ("Who is the buyer named on the invoice?", "northwind traders"),
    ("Who is the vendor named on the invoice?", "acme supplies"),
    ("What service is billed on the invoice?", "consulting services"),
    ("How many units were invoiced?", "10 units"),
    ("What currency is the invoice denominated in?", "inr"),
    ("What payment terms are stated on the invoice?", "net 30"),
    ("What early payment discount does the vendor grant?", "300.00"),
    ("Under what condition is the discount granted?", "early-settlement"),
    ("Does the policy allow full settlement below the invoiced total?", "closing the invoice"),
    ("What is the name of the vendor payment policy document?", "vendor payment policy"),
    ("Which company issued the vendor payment policy?", "acme supplies private limited"),
    ("Which invoice number does the vendor policy apply to?", "inv-2026-0001"),
    ("What kind of discount is described in the policy?", "early payment discount"),
    ("Within what window must the buyer settle to earn the discount?", "settles in full"),
    ("What is the principal of the synthetic loan?", "500,000.00"),
    ("What is the annual interest rate in the loan agreement?", "9.5 percent"),
    ("How many employees are listed in the payroll summary?", "12"),
    ("What is the gross payroll amount?", "480,000.00"),
    ("What is the rent payment deadline in the Prime Properties policy?", "7 calendar days"),
    ("What is the late rent payment fee?", "2 percent"),
    ("How much was paid for the January invoice settlement?", "11,700.00"),
    ("What is the amount of the office rent transaction?", "25,000.00"),
    ("How much was spent on travel expenses?", "8,400.00"),
    ("How much was spent on office supplies?", "3,200.00"),
    ("What is the repayment term of the demo loan?", "24 months"),
]

UNANSWERABLE_QUESTIONS = [
    "What is the account holder's passport number?",
    "What was the company's exact electricity bill in December 2025?",
    "Which employee received the largest annual bonus?",
    "What is the GST registration number of Prime Properties?",
    "What was the closing bank balance on 31 January 2026?",
    "Who is the chief financial officer's home address?",
    "What is the loan's prepayment penalty amount?",
    "How many laptops were purchased in February 2026?",
]


def chunk_details(chunk):
    """Return stable identifiers and location for an indexed chunk."""
    return {
        "chunk_id": chunk.id,
        "document_id": chunk.document_id,
        "chunk_index": chunk.chunk_index,
        "page_number": chunk.page_number,
    }


def expected_evidence_chunks(db, phrase):
    """Find all indexed chunks containing the expected evidence phrase."""
    chunks = (
        db.query(DocumentChunk)
        .filter(DocumentChunk.organization_id == ORG)
        .all()
    )

    return [
        chunk_details(chunk)
        for chunk in chunks
        if phrase.casefold() in chunk.content.casefold()
    ]


def retrieved_chunk_details(db, results):
    """Resolve retrieved content to indexed chunk identifiers."""
    details = []

    for result in results:
        content = result.get("content") or ""

        chunk = (
            db.query(DocumentChunk)
            .filter(
                DocumentChunk.organization_id == ORG,
                DocumentChunk.content == content,
            )
            .first()
        )

        details.append({
            **(chunk_details(chunk) if chunk else {}),
            "score": result.get("score"),
            "content": content,
        })

    return details


def main():
    init_db()
    db = SessionLocal()

    try:
        embedder = SentenceTransformerEmbeddingProvider()

        pdf_files = sorted(DATA_DIR.glob("*.pdf"))
        if not pdf_files:
            raise FileNotFoundError(
                f"No synthetic PDFs found in {DATA_DIR}. "
                "Run generate_fixtures.py first."
            )

        for path in pdf_files:
            raw = path.read_bytes()
            _, pages = document_parser.extract_pdf_text(raw)

            if not pages:
                raise RuntimeError(f"No text extracted from {path.name}")

            doc = Document(
                id=str(uuid.uuid4()),
                organization_id=ORG,
                original_filename=path.name,
                document_type="synthetic",
                processing_status="completed",
                page_count=len(pages),
                file_size=len(raw),
                file_hash=document_parser.compute_file_hash(raw),
            )
            db.add(doc)
            db.flush()

            for page in pages:
                db.add(
                    DocumentPage(
                        id=str(uuid.uuid4()),
                        organization_id=ORG,
                        document_id=doc.id,
                        page_number=page["page"],
                        content=page["text"],
                        char_count=len(page["text"]),
                    )
                )

            db.commit()
            indexing_service.index_document(db, doc, embedder)

        corpus_chunks = (
            db.query(DocumentChunk)
            .filter(DocumentChunk.organization_id == ORG)
            .count()
        )

        if corpus_chunks == 0:
            raise RuntimeError("Indexing completed but produced no chunks.")

        embedder.embed_query("warm up")

        answerable_rows = []
        reciprocal_ranks = []
        hit1 = 0
        hit5 = 0

        for question, expected in ANSWERABLE_QUESTIONS:
            results = retrieval_service.retrieve(
                db, question, ORG, embedder, top_k=5
            )

            matching_rank = None

            for rank, result in enumerate(results, start=1):
                content = (result.get("content") or "").casefold()
                if expected.casefold() in content:
                    matching_rank = rank
                    break

            found_at_1 = matching_rank == 1
            found_at_5 = matching_rank is not None and matching_rank <= 5

            hit1 += int(found_at_1)
            hit5 += int(found_at_5)

            reciprocal_ranks.append(
                1.0 / matching_rank if matching_rank is not None else 0.0
            )

            answerable_rows.append({
                "question": question,
                "expected_evidence": expected,
                "expected_evidence_chunks": expected_evidence_chunks(
                    db, expected
                ),
                "matching_rank": matching_rank,
                "hit_at_1": found_at_1,
                "hit_at_5": found_at_5,
                "top_score": results[0].get("score") if results else None,
                "retrieved_chunks": retrieved_chunk_details(db, results),
            })

        abstention_rows = []
        threshold = float(settings.RAG_MIN_SCORE)

        for question in UNANSWERABLE_QUESTIONS:
            results = retrieval_service.retrieve(
                db, question, ORG, embedder, top_k=5
            )

            top_score = float(results[0]["score"]) if results else None

            # This evaluates threshold-based abstention in the benchmark.
            # It does not imply production retrieval enforces this threshold.
            abstained = top_score is None or top_score < threshold

            abstention_rows.append({
                "question": question,
                "expected_evidence_chunks": [],
                "top_score": top_score,
                "threshold": threshold,
                "abstained": abstained,
                "retrieved_chunks": retrieved_chunk_details(db, results),
            })

        total_answerable = len(ANSWERABLE_QUESTIONS)
        total_unanswerable = len(UNANSWERABLE_QUESTIONS)

        abstention_passes = sum(
            row["abstained"] for row in abstention_rows
        )

        output = {
            "corpus_documents": len(pdf_files),
            "corpus_chunks": corpus_chunks,
            "answerable_questions": total_answerable,
            "unanswerable_questions": total_unanswerable,
            "hit_at_1_pct": round(100 * hit1 / total_answerable, 2),
            "hit_at_5_pct": round(100 * hit5 / total_answerable, 2),
            "mrr": round(sum(reciprocal_ranks) / total_answerable, 4),
            "rag_min_score": threshold,
            "abstention_passed": abstention_passes,
            "abstention_total": total_unanswerable,
            "abstention_accuracy_pct": round(
                100 * abstention_passes / total_unanswerable, 2
            ),
            "answerable_results": answerable_rows,
            "abstention_results": abstention_rows,
        }

        output_path = BACKEND_DIR / "scripts" / "retrieval_hit_results.json"
        output_path.write_text(
            json.dumps(output, indent=2),
            encoding="utf-8",
        )

        summary = {
            key: value
            for key, value in output.items()
            if key not in ("answerable_results", "abstention_results")
        }

        print(json.dumps(summary, indent=2))
        print(
            "Missed at top-1:",
            [
                row["question"]
                for row in answerable_rows
                if not row["hit_at_1"]
            ],
        )
        print(
            "Abstention failures:",
            [
                row["question"]
                for row in abstention_rows
                if not row["abstained"]
            ],
        )
        print(f"Results written to: {output_path}")

    finally:
        db.close()


if __name__ == "__main__":
    main()
